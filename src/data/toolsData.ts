// Get sub-techniques for a parent tool
export function getSubTechniques(parentId: string) {
  return subTechniques.filter((st) => st.parentTool === parentId);
}

// Get main tool by ID
export function getMainTool(id: string) {
  return mainTools.find((t) => t.id === id);
}

// Get sub-technique by ID
export function getSubTechnique(id: string) {
  return subTechniques.find((st) => st.id === id);
}
